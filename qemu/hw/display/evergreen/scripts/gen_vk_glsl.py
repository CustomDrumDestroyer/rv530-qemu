#!/usr/bin/env python3
"""Embed eg_vk_frag.glsl into eg_vk_glsl.h (run after editing it)."""
import os, json
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'eg_vk_frag.glsl')).read()
out = ['/* Generated by scripts/gen_vk_glsl.py from eg_vk_frag.glsl. Do not edit. */',
       'static const char evk_frag_glsl[] =']
for line in src.splitlines():
    out.append('    ' + json.dumps(line + '\n'))
out[-1] += ';'
open(os.path.join(here, '..', 'eg_vk_glsl.h'), 'w').write('\n'.join(out) + '\n')
